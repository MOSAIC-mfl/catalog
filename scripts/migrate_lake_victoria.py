def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--source", required=True, type=Path, help="checkout of mosaic-lake-victoria (read only)")
    args = ap.parse_args()
    reg = {layer["id"]: layer for layer in read_json(args.source, "data/meta/layers.json")["layers"]}
    OUT.mkdir(parents=True, exist_ok=True)
    write_yaml("profile.yaml", profile(), "MOSAIC landscape profile: Lake Victoria Basin (KEN-LVB)")
    write_yaml("explorer.yaml", explorer(reg), "Map explorer of the KEN-LVB profile")
    write_yaml("story.yaml", story(args.source), "Story of the KEN-LVB explorer")
    write_yaml("studies.yaml", studies(args.source), "Studies of the KEN-LVB explorer")
    write_yaml("sources.yaml", sources(reg), "Sources of the KEN-LVB explorer layers (from its data/meta/layers.json)")
    review = ROOT / "review" / "landscape_KEN-LVB_sources.md"
    rows = [
        f"| {lid} | {lyr.get('title', '')} | {lyr.get('source', '')} | {lyr.get('licence', '')} |"
        for lid, lyr in reg.items()
    ]
    review.write_text(
        "# KEN-LVB explorer: layers to register in the catalogue\n\n"
        "The explorer's layers are described in landscapes/KEN-LVB/sources.yaml with the texts of their author. "
        "None is a catalogue record yet: ids are assigned by the team. Once a layer is registered, set `record: "
        "mosaic:<id>` in sources.yaml (and on the overlay in explorer.yaml) and the website links it.\n\n"
        "Licences to confirm before publishing: ICPAC basin boundary (not specified, withheld), DAHITI lake level "
        "(non-commercial), HydroSHEDS rivers (display only, no redistribution).\n\n"
        "| Layer | Title | Source | Licence |\n|---|---|---|---|\n" + "\n".join(rows) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(ROOT)}/: profile, explorer, story, studies, sources; {review.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
