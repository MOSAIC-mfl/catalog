def read_json(source: Path, rel: str) -> Any:
    return json.loads((source / rel).read_text(encoding="utf-8"))


def write_yaml(name: str, data: dict[str, Any], what: str) -> None:
    head = (
        f"# {what}\n# Generated by scripts/migrate_lake_victoria.py from {REPO} @ {COMMIT} (read only).\n"
        "# Schema: schema/landscape/ (python -m mosaic_catalog validate-landscapes).\n"
    )
    (OUT / name).write_text(head + dump(data), encoding="utf-8")


