    reg = {layer["id"]: layer for layer in read_json(args.source, "data/meta/layers.json")["layers"]}
    OUT.mkdir(parents=True, exist_ok=True)
    write_yaml("profile.yaml", profile(), f"MOSAIC landscape profile: Pucallpa – Ucayali ({CODE})")
    write_yaml("explorer.yaml", explorer(reg), f"Map explorer of the {CODE} profile")
    write_yaml("story.yaml", story(args.source), f"Story of the {CODE} explorer")
    write_yaml("studies.yaml", studies(args.source), f"Studies of the {CODE} explorer")
    write_yaml("sources.yaml", sources(reg), f"Sources of the {CODE} explorer layers (from its data/meta/layers.json)")
    review = ROOT / "review" / f"landscape_{CODE}_sources.md"
    rows = [
        f"| {lid} | {lyr.get('title', '')} | {lyr.get('licence', '')} | {RELATED.get(lid, '')} |"
        for lid, lyr in reg.items()
    ]
    review.write_text(
        f"# {CODE} explorer: layers to register in the catalogue\n\n"
        f"The explorer's layers are described in landscapes/{CODE}/sources.yaml with the texts of their author. "
        "None is a catalogue record yet: ids are assigned by the team. Some catalogue records describe products "
        "derived from the same sources (last column); they are not the files the explorer shows, so they are not "
        "linked. Once a layer is registered, set `record: mosaic:<id>` in sources.yaml (and on the overlay in "
        "explorer.yaml) and the website links it.\n\n"
        "Licences to confirm before publishing: terrain (DEM provenance open; assumed Copernicus GLO-30, see the data "
        "report), GEOBOSQUES forest loss (no licence stated, citation required), SERNANP protected areas (derived maps "
        "authorised, no commercial use, original data not redistributed). Not hosted: RAISG Indigenous territories "
        "(licence and sensitivity).\n\n"
        "| Layer | Title | Licence | Related catalogue records |\n|---|---|---|---|\n" + "\n".join(rows) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(ROOT)}/: profile, explorer, story, studies, sources; {review.relative_to(ROOT)}")
    return 0


