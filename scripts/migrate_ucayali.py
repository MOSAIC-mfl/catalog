def steps_legend(
    title: str, colors: list[str], labels: list[str], notes: list[str], source: str | None
) -> dict[str, Any]:
    out: dict[str, Any] = {"kind": "steps", "title": title, "colors": colors, "labels": labels}
    if notes:
        out["notes"] = notes
    if source:
        out["source"] = source
    return out


