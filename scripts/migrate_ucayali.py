"""Convert the MOSAIC Ucayali Explorer into a MOSAIC landscape profile (landscapes/PER-PCL/).

    python scripts/migrate_ucayali.py --source D:/Code/Mosaic/mosaic-ucayali

The source repository is only READ (its own JSON files: data/meta/layers.json, story_chapters.json,
studies.json). What the explorer keeps in JavaScript (the overlay list, legends, click texts, map
style, colours, chart definitions) is transcribed below from site/js/*.js at commit 24fbe3a, so the
profile shows what the explorer shows. Nothing is invented: every text comes from the explorer; where
the explorer has no value the profile has none either.

The explorer was scaffolded from the Lake Victoria Basin Explorer, so most of it maps onto the same
website modules (raster-tiles, year-tiles, climate-grid, index-grid). Its vector layers (vegetation
classes, protected areas, GEDI footprints) use the core `style-layers` renderer and the
`feature-attributes` / `value-at-point` / `series-values` / `combined` inspectors; its story charts
use the `class-bars` builder. No profile plugin is needed.

Written files (regenerated each run, hand edits are overwritten - edit the profile afterwards, not this
script, once the team adopts it):

    landscapes/PER-PCL/profile.yaml     the page: sections and credits
    landscapes/PER-PCL/explorer.yaml    the map explorer: data, map style, layers
    landscapes/PER-PCL/story.yaml       "The forest-agriculture interface of Ucayali" (chapters)
    landscapes/PER-PCL/studies.yaml     question cards with verified findings
    landscapes/PER-PCL/sources.yaml     source, licence, citation and caveats of each layer
    review/landscape_PER-PCL_sources.md layers to register in the catalogue, licences to confirm
"""

