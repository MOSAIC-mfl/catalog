def _time(layer: str | None, t: Any) -> dict[str, Any] | None:
    """A chip's time as the website's preset parameters: a month for SPI-3, else a year."""
    if t is None:
        return None
    return {"month": str(t)} if layer == "spi3" else {"year": int(t)}


def _camera(cam: dict[str, Any] | None, fill: float | None = None) -> dict[str, Any] | None:
    """Bounds cameras keep the box and get its centre as lng/lat (the website's camera always has them)."""
    if not cam:
        return None
    out = dict(cam)
    b = out.get("bounds")
    if b:
        out.setdefault("lng", round((b[0] + b[2]) / 2, 5))
        out.setdefault("lat", round((b[1] + b[3]) / 2, 5))
        if fill:
            out.setdefault("fill", fill)
    return out


