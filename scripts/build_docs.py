#!/usr/bin/env python3
"""Generate docs/fields.md (field reference) from the schemas, so the docs cannot drift.

Same walk of the schemas as scripts/build_reference.py (fields.xlsx, record-reference.yaml).

python3 scripts/build_docs.py          # write docs/fields.md
python3 scripts/build_docs.py --check  # exit 1 if it is out of date (CI)
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "fields.md"


def _reference():  # type: ignore[no-untyped-def]
    spec = importlib.util.spec_from_file_location("build_reference", ROOT / "scripts" / "build_reference.py")
    if spec is None or spec.loader is None:
        raise ImportError("scripts/build_reference.py not found")
    mod = importlib.util.module_from_spec(spec)
    sys.modules["build_reference"] = mod  # dataclasses look the module up while it loads
    spec.loader.exec_module(mod)
    return mod


def cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def build() -> str:
    ref = _reference()
    w = ref.Walker()
    w.walk(w.rec["properties"], "", 0, set())
    version = w.rec["$id"].rsplit("/v", 1)[1].split("/")[0]
    lines = [
        f"# MOSAIC record fields (v{version})",
        "",
        "Generated by `scripts/build_docs.py` from `schema/`. Do not edit by hand.",
        "",
        "Built on the CGIAR Climate Data Hub core (v0.5.0): the CDH column gives the same field in CDH "
        "(empty = MOSAIC only); the v0.1 column gives the name in the previous MOSAIC version (empty = new).",
        "",
        "Levels: **Mínimo** = required to be complete (missing -> `review/minimum_gaps`); Recomendado = "
        "warning; Perfil MOSAIC = warning until enforced in `mosaic.config.yaml`; Automático = written by the "
        "build; Opcional = no check. A field with a wrong shape makes the record invalid whatever its level.",
        "",
        "| Field | Level | Type | Meaning | CDH | v0.1 |",
        "|---|---|---|---|---|---|",
    ]
    for r in w.rows:
        level = f"**{r.level}**" if r.level == ref.MIN else r.level
        if r.condition:
            level += f" ({cell(r.condition)})"
        name = ("&nbsp;&nbsp;" * r.depth) + f"`{r.path}`"
        desc = cell(r.description)[:300]
        lines.append(f"| {name} | {level} | {cell(r.type)} | {desc} | {cell(r.cdh)} | {cell(r.schema1)} |")

    lines += ["", "## Rules beyond presence", ""]
    for lv_name, schema in (("minimum", w.min), ("recommended", w.recm)):
        msgs = [r["x-message"] for r in schema.get("allOf", []) if "x-message" in r]
        msgs += [p["x-message"] for p in schema.get("properties", {}).values() if "x-message" in p]
        lines += [f"- {lv_name}: {m}" for m in msgs]
    prof = json.loads((ROOT / "schema" / "profiles" / "mosaic.schema.json").read_text(encoding="utf-8"))
    lines += [f"- profile `mosaic`: {p['x-message']}" for p in prof["properties"].values() if "x-message" in p]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = build()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("docs/fields.md is out of date (run scripts/build_docs.py)")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
