#!/usr/bin/env python3
"""Generate docs/fields.md (field reference) from the schemas, so the docs cannot drift.

python3 scripts/build_docs.py          # write docs/fields.md
python3 scripts/build_docs.py --check  # exit 1 if it is out of date (CI)
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "schema"
OUT = ROOT / "docs" / "fields.md"


def load(rel: str) -> dict[str, Any]:
    data: dict[str, Any] = json.loads((SCHEMA / rel).read_text(encoding="utf-8"))
    return data


def type_of(node: dict[str, Any], defs: dict[str, Any]) -> str:
    if "$ref" in node:
        ref = node["$ref"]
        if ref.startswith("vocab.schema.json"):
            name = ref.rsplit("/", 1)[1]
            return f"vocab `{name}`"
        name = ref.rsplit("/", 1)[1]
        target = defs.get(name, {})
        if target.get("type") == "object":
            return f"object `{name}`"
        return type_of(target, defs) if target else name
    if "oneOf" in node:
        return " or ".join(type_of(n, defs) for n in node["oneOf"])
    t = node.get("type", "")
    if t == "array":
        return f"list of {type_of(node.get('items', {}), defs)}"
    if isinstance(t, list):
        return " / ".join(t)
    if "enum" in node:
        return "one of " + ", ".join(f"`{v}`" for v in node["enum"])
    return t or "any"


def description(node: dict[str, Any], defs: dict[str, Any]) -> str:
    if "description" in node:
        return str(node["description"])
    if "$ref" in node and not node["$ref"].startswith("vocab"):
        return str(defs.get(node["$ref"].rsplit("/", 1)[1], {}).get("description", ""))
    return ""


def build() -> str:
    rec = load("record.schema.json")
    defs = rec["$defs"]
    minimum = load("levels/minimum.schema.json")
    rec_lv = load("levels/recommended.schema.json")
    mosaic = load("profiles/mosaic.schema.json")
    level: dict[str, str] = {}
    for f in rec_lv.get("required", []):
        level[f] = "recommended"
    for f in minimum["required"]:
        level[f] = "**minimum**"
    level["citation"] = "**minimum** (citation or doi)"
    level["doi"] = "**minimum** (citation or doi)"
    level["access_note"] = "**minimum** if access is not public"
    level["mosaic"] = "profile `mosaic`"
    for f in ("created", "updated"):
        level[f] = "recommended (machine-filled)"

    lines = [
        "# MOSAIC record fields (v" + rec["$id"].rsplit("/v", 1)[1].split("/")[0] + ")",
        "",
        "Generated by `scripts/build_docs.py` from `schema/`. Do not edit by hand.",
        "",
        "Levels: **minimum** = required to be complete (missing -> listed in `review/`); "
        "recommended = warning; profile `mosaic` = warning until enforced in `mosaic.config.yaml`; "
        "optional = no check.",
        "",
        "## Record",
        "",
        "| Field | Type | Level | Meaning |",
        "|---|---|---|---|",
    ]
    for name, node in rec["properties"].items():
        desc = description(node, defs).replace("|", "\\|")
        lines.append(f"| `{name}` | {type_of(node, defs)} | {level.get(name, 'optional')} | {desc} |")

    lines += ["", "## Rules beyond presence", ""]
    for lv_name, schema in (("minimum", minimum), ("recommended", rec_lv)):
        msgs = [r["x-message"] for r in schema.get("allOf", []) if "x-message" in r]
        msgs += [p["x-message"] for p in schema.get("properties", {}).values() if "x-message" in p]
        lines += [f"- {lv_name}: {m}" for m in msgs]
    req = ", ".join(f"`{f}`" for f in mosaic["properties"]["mosaic"]["required"])
    lines.append(f"- profile `mosaic`: id `MFL-YYYY-NNN` and `mosaic` with {req}")

    for obj in (
        "license",
        "contact",
        "citation",
        "accessPoint",
        "temporal",
        "spatial",
        "related",
        "rasterBlock",
        "vectorBlock",
        "tabularBlock",
        "documentBlock",
        "serviceBlock",
        "mosaicBlock",
    ):
        node = defs[obj]
        lines += ["", f"## `{obj}`", ""]
        if node.get("description"):
            lines += [node["description"], ""]
        req = set(node.get("required", []))
        lines += ["| Field | Type | Required in the object | Meaning |", "|---|---|---|---|"]
        for name, sub in node.get("properties", {}).items():
            desc = description(sub, defs).replace("|", "\\|")
            lines.append(f"| `{name}` | {type_of(sub, defs)} | {'yes' if name in req else ''} | {desc} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = build()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("docs/fields.md is out of date (run scripts/build_docs.py)")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
